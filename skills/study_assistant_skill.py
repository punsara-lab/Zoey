def get_ai_recommendation(query: str) -> str:
    """Recommend which AI service to use based on query type."""
    query_lower = query.lower()
    
    # Math/Computation
    if any(k in query_lower for k in [
        "calculate", "solve", "equation", "integral", "derivative",
        "formula", "math", "algebra", "geometry", "statistics"
    ]):
        return "wolfram"
    
    # Research/Facts
    if any(k in query_lower for k in [
        "research", "what is", "how does", "explain", "compare",
        "difference between", "history of", "latest", "news"
    ]):
        return "perplexity"
    
    # Code/Programming
    if any(k in query_lower for k in [
        "code", "program", "debug", "function", "script",
        "python", "javascript", "error", "fix"
    ]):
        return "claude"
    
    # Images/Creatives
    if any(k in query_lower for k in [
        "image", "picture", "diagram", "draw", "create visual"
    ]):
        return "dalle"
    
    # Default
    return "openrouter"


