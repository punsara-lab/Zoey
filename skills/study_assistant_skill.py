def start_study_session(args: dict) -> str:
    """Start a new study session with tracking."""
    topic = (args.get("topic") or "General Study").strip()
    goal = (args.get("goal") or "Learn and understand the topic").strip()
    duration = int(args.get("duration_minutes") or 0)
    
    os.makedirs(STUDY_DIR, exist_ok=True)
    
    session_id = f"study_{int(time.time())}_{re.sub(r'[^a-z0-9]', '_', topic.lower())[:30]}"
    session_file = os.path.join(STUDY_DIR, f"{session_id}.json")
    
    session_data = {
        "id": session_id,
        "topic": topic,
        "goal": goal,
        "started_at": datetime.now().isoformat(),
        "scheduled_duration": duration,
        "status": "active",
        "notes": [],
        "resources": [],
        "questions": [],
        "breakthroughs": [],
    }
    
    with open(session_file, "w", encoding="utf-8") as f:
        json.dump(session_data, f, indent=2)
    
    return (
        f"Started study session: **{topic}**\n"
        f"Goal: {goal}\n"
        f"Session ID: `{session_id}`\n"
        f"Type `pause study` to take a break, `end study` to finish."
    )


def add_study_note(args: dict) -> str:
    """Add a note to the current study session."""
    content = (args.get("content") or "").strip()
    note_type = (args.get("type") or "general").strip()
    source = (args.get("source") or "").strip()
    
    if not content:
        return "Please provide note content."
    
    # Find active session
    os.makedirs(STUDY_DIR, exist_ok=True)
    active_session = None
    session_file = None
    
    for fname in sorted(os.listdir(STUDY_DIR), reverse=True):
        if fname.startswith("study_") and fname.endswith(".json"):
            fpath = os.path.join(STUDY_DIR, fname)
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                if data.get("status") == "active":
                    active_session = data
                    session_file = fpath
                    break
            except Exception:
                continue
    
    if not active_session:
        return "No active study session. Start one with: study topic: [your topic]"
    
    note = {
        "timestamp": datetime.now().isoformat(),
        "type": note_type,
        "content": content,
        "source": source,
    }
    
    active_session["notes"].append(note)
    
    with open(session_file, "w", encoding="utf-8") as f:
        json.dump(active_session, f, indent=2)
    
    return f"Added {note_type} note to study session. Total notes: {len(active_session['notes'])}"


def end_study_session(args: dict) -> str:
    """End the current study session and generate summary."""
    summary_only = bool(args.get("summary_only"))
    
    os.makedirs(STUDY_DIR, exist_ok=True)
    active_session = None
    session_file = None
    
    for fname in sorted(os.listdir(STUDY_DIR), reverse=True):
        if fname.startswith("study_") and fname.endswith(".json"):
            fpath = os.path.join(STUDY_DIR, fname)
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                if data.get("status") == "active":
                    active_session = data
                    session_file = fpath
                    break
            except Exception:
                continue
    
    if not active_session:
        return "No active study session to end."
    
    # Calculate duration
    started = datetime.fromisoformat(active_session["started_at"])
    ended = datetime.now()
    duration = ended - started
    duration_mins = int(duration.total_seconds() / 60)
    
    active_session["status"] = "completed"
    active_session["ended_at"] = ended.isoformat()
    active_session["duration_minutes"] = duration_mins
    
    with open(session_file, "w", encoding="utf-8") as f:
        json.dump(active_session, f, indent=2)
    
    summary = f"""## Study Session Complete!

**Topic:** {active_session['topic']}
**Goal:** {active_session['goal']}
**Duration:** {duration_mins} minutes
**Notes Taken:** {len(active_session['notes'])}
**Resources:** {len(active_session['resources'])}

### Session saved to:
`{session_file}`

Use `review study` to see a summary or export your notes."""
    
    return summary


