def deep_research(args: dict) -> str:
    """
    Multi-step research workflow:
    1. Search for current information
    2. Call external AI for synthesis
    3. Generate structured notes
    """
    query = (args.get("query") or "").strip()
    depth = (args.get("depth") or "medium").lower()
    save = bool(args.get("save", True))
    
    if not query:
        return "Please provide a research query."
    
    os.makedirs(STUDY_DIR, exist_ok=True)
    
    # Step 1: Web search for current info
    try:
        from research_skill import research_topic
        search_results = research_topic({"topic": query, "max_results": 5 if depth == "shallow" else 10})
    except Exception as e:
        search_results = f"Search error: {e}"
    
    # Step 2: Call external AI for synthesis
    synthesis_prompt = f"""Research Query: {query}

Search Results:
{search_results[:3000]}

Please provide:
1. A concise summary of the topic (3-5 sentences)
2. Key findings or main points (bullet points)
3. Important technical details or data
4. Related concepts to explore
5. Any uncertainties or areas needing more research

Format for a study note."""

    synthesis = _call_openrouter(synthesis_prompt, {"max_tokens": 1500})
    
    # Step 3: Generate structured notes
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_query = re.sub(r'[^a-z0-9]+', '_', query.lower())[:30]
    note_path = os.path.join(STUDY_DIR, f"research_{safe_query}_{timestamp}.md")
    
    note_content = f"""# Research: {query}

**Date:** {datetime.now().strftime('%Y-%m-%d %H:%M')}
**Depth:** {depth}
**Query:** {query}

## Summary

{synthesis}

## Raw Search Results

```
{search_results}
```

## Next Steps

- [ ] Review and verify key findings
- [ ] Cross-reference with additional sources
- [ ] Integrate into main study notes

---
*Generated by ZOEY Deep Research*
"""
    
    if save:
        with open(note_path, "w", encoding="utf-8") as f:
            f.write(note_content)
        result_msg = f"Research complete! Saved to: `{note_path}`"
    else:
        result_msg = "Research complete! (not saved)"
    
    return (
        f"{result_msg}\n\n"
        f"**Query:** {query}\n"
        f"**Synthesis Preview:**\n{synthesis[:500]}...\n\n"
        f"Use `export study notes` to save to a different format."
    )


def export_study_notes(args: dict) -> str:
    """Export study notes to various formats."""
    session_id = (args.get("session") or "").strip()
    format_type = (args.get("format") or "markdown").lower()
    
    if not session_id:
        return "Please specify a study session ID."
    
    # Find the session
    session_file = os.path.join(STUDY_DIR, f"{session_id}.json")
    if not os.path.exists(session_file):
        return f"Study session not found: {session_id}"
    
    with open(session_file, "r", encoding="utf-8") as f:
        session = json.load(f)
    
    if format_type == "markdown":
        return _export_to_markdown(session)
    elif format_type == "anki":
        return _export_to_anki(session)
    elif format_type == "pdf":
        return _export_to_pdf(session)
    else:
        return f"Unsupported format: {format_type}. Use: markdown, anki, or pdf."


def _export_to_markdown(session: dict) -> str:
    """Export session to a formatted markdown file."""
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"{session['id']}_{timestamp}.md"
    filepath = os.path.join(STUDY_DIR, filename)
    
    lines = [
        f"# Study Notes: {session['topic']}",
        "",
        f"**Goal:** {session['goal']}",
        f"**Started:** {session['started_at']}",
        f"**Duration:** {session.get('duration_minutes', 'N/A')} minutes",
        "",
        "---",
        "",
        "## Session Notes",
        "",
    ]
    
    for note in session.get("notes", []):
        lines.append(f"### {note['type'].upper()} - {note['timestamp']}")
        if note.get('source'):
            lines.append(f"**Source:** {note['source']}")
        lines.append("")
        lines.append(note['content'])
        lines.append("")
    
    lines.extend([
        "---",
        "",
        "## Resources Used",
        "",
    ])
    
    for resource in session.get("resources", []):
        lines.append(f"- {resource}")
    
    lines.extend([
        "",
        "---",
        "",
        "*Generated by ZOEY Study Assistant*",
    ])
    
    with open(filepath, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    
    return f"Exported to: `{filepath}`"


def _export_to_anki(session: dict) -> str:
    """Export notes to Anki flashcard format."""
    lines = ["#separator:Tab", "#html:false", "#tags:zoey_study"]
    
    for note in session.get("notes", []):
        if note['type'] in ['question', 'key_point', 'definition']:
            # Front: Question/Key point, Back: Answer/Explanation
            front = note['content'][:200]
            back = note.get('source', 'Review your notes for the full answer.')
            lines.append(f'{front}\t{back}')
    
    filename = f"{session['id']}_anki.txt"
    filepath = os.path.join(STUDY_DIR, filename)
    
    with open(filepath, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    
    return f"Anki deck exported to: `{filepath}`\nImport in Anki: File → Import → select this file."


def _export_to_pdf(session: dict) -> str:
    """Export session to PDF."""
    try:
        from weasyprint import HTML, CSS
        
        # Create HTML content
        html_content = f"""
        <!DOCTYPE html>
        <html>
        <head>
            <style>
                body {{ font-family: Arial, sans-serif; margin: 40px; }}
                h1 {{ color: #333; border-bottom: 2px solid #666; }}
                h2 {{ color: #555; margin-top: 30px; }}
                .meta {{ color: #666; font-style: italic; }}
                .note {{ background: #f5f5f5; padding: 10px; margin: 10px 0; border-left: 3px solid #666; }}
            </style>
        </head>
        <body>
            <h1>Study Notes: {session['topic']}</h1>
            <p class="meta">Goal: {session['goal']}</p>
            <p class="meta">Started: {session['started_at']}</p>
            <p class="meta">Duration: {session.get('duration_minutes', 'N/A')} minutes</p>
            
            <h2>Session Notes</h2>
        """
        
        for note in session.get("notes", []):
            html_content += f"""
            <div class="note">
                <strong>{note['type'].upper()}</strong> - {note['timestamp']}<br>
                {note['content'][:500]}
            </div>
            """
        
        html_content += """
        </body>
        </html>
        """
        
        filename = f"{session['id']}.pdf"
        filepath = os.path.join(STUDY_DIR, filename)
        
        HTML(string=html_content).write_pdf(filepath)
        
        return f"PDF exported to: `{filepath}`"
        
    except ImportError:
        return "PDF export requires 'weasyprint'. Install with: pip install weasyprint"
    except Exception as e:
        return f"PDF export failed: {e}"


