def call_external_ai(args: dict) -> str:
    """Call an external AI service for specialized help."""
    service = (args.get("service") or "auto").lower()
    prompt = (args.get("prompt") or "").strip()
    context = (args.get("context") or "").strip()
    
    if not prompt:
        return "Please provide a prompt for the AI."
    
    # Build the full prompt with context
    full_prompt = prompt
    if context:
        full_prompt = f"Context:\n{context}\n\nTask:\n{prompt}"
    
    # Auto-select service based on prompt content
    if service == "auto":
        if any(k in prompt.lower() for k in ["code", "program", "debug", "function", "script"]):
            service = "github_copilot" if _check_copilot_available() else "openrouter"
        elif any(k in prompt.lower() for k in ["math", "equation", "calculate", "solve"]):
            service = "wolfram" if _check_wolfram_available() else "openrouter"
        elif any(k in prompt.lower() for k in ["image", "picture", "draw", "diagram"]):
            service = "dalle" if _check_dalle_available() else "openrouter"
        else:
            service = "openrouter"
    
    # Call appropriate service
    if service == "openrouter":
        return _call_openrouter(full_prompt, args)
    elif service == "claude":
        return _call_claude(full_prompt, args)
    elif service == "perplexity":
        return _call_perplexity(full_prompt, args)
    elif service == "wolfram":
        return _call_wolfram(prompt, args)
    else:
        return _call_openrouter(full_prompt, args)


def _call_openrouter(prompt: str, args: dict) -> str:
    """Call OpenRouter API."""
    import api
    
    try:
        client = api.make_client()
        messages = [
            {"role": "system", "content": "You are a helpful study and research assistant. Be concise but thorough."},
            {"role": "user", "content": prompt}
        ]
        
        model = args.get("model", "anthropic/claude-3.5-sonnet")
        response = client.chat.completions.create(
            model=model,
            messages=messages,
            temperature=float(args.get("temperature", 0.7)),
            max_tokens=int(args.get("max_tokens", 2000))
        )
        
        return response.choices[0].message.content
    except Exception as e:
        return f"OpenRouter call failed: {e}"


def _call_claude(prompt: str, args: dict) -> str:
    """Call Anthropic Claude directly."""
    import os
    
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        return "ANTHROPIC_API_KEY not set. Using OpenRouter fallback..."
    
    try:
        import requests
        
        headers = {
            "x-api-key": api_key,
            "content-type": "application/json",
        }
        
        data = {
            "model": args.get("model", "claude-3-5-sonnet-20241022"),
            "max_tokens": int(args.get("max_tokens", 2000)),
            "messages": [{"role": "user", "content": prompt}],
        }
        
        resp = requests.post(
            "https://api.anthropic.com/v1/messages",
            headers=headers,
            json=data,
            timeout=60
        )
        
        if resp.status_code == 200:
            return resp.json()["content"][0]["text"]
        else:
            return f"Claude API error: {resp.status_code} - {resp.text}"
    except Exception as e:
        return f"Claude call failed: {e}"


def _call_perplexity(prompt: str, args: dict) -> str:
    """Call Perplexity API for research."""
    import os
    
    api_key = os.getenv("PERPLEXITY_API_KEY")
    if not api_key:
        return "PERPLEXITY_API_KEY not set. Using OpenRouter fallback..."
    
    try:
        import requests
        
        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json"
        }
        
        data = {
            "model": args.get("model", "sonar-pro"),
            "messages": [
                {"role": "system", "content": "Be thorough and cite your sources."},
                {"role": "user", "content": prompt}
            ]
        }
        
        resp = requests.post(
            "https://api.perplexity.ai/chat/completions",
            headers=headers,
            json=data,
            timeout=60
        )
        
        if resp.status_code == 200:
            result = resp.json()
            content = result["choices"][0]["message"]["content"]
            # Include citations if available
            citations = result.get("citations", [])
            if citations:
                content += "\n\n**Sources:**\n" + "\n".join(f"- {c}" for c in citations[:5])
            return content
        else:
            return f"Perplexity API error: {resp.status_code}"
    except Exception as e:
        return f"Perplexity call failed: {e}"


def _call_wolfram(prompt: str, args: dict) -> str:
    """Call Wolfram Alpha for computational queries."""
    import os
    
    app_id = os.getenv("WOLFRAM_APP_ID")
    if not app_id:
        return "WOLFRAM_APP_ID not set. This is needed for math/computation queries."
    
    try:
        import urllib.parse
        import urllib.request
        
        query = urllib.parse.quote(prompt)
        url = f"http://api.wolframalpha.com/v2/query?input={query}&appid={app_id}&format=plaintext&output=json"
        
        with urllib.request.urlopen(url, timeout=30) as response:
            data = json.loads(response.read().decode())
        
        if data.get("queryresult", {}).get("success"):
            pods = data["queryresult"].get("pods", [])
            results = []
            for pod in pods[:3]:
                title = pod.get("title", "")
                subpods = pod.get("subpods", [])
                for sub in subpods:
                    text = sub.get("plaintext", "")
                    if text:
                        results.append(f"**{title}:** {text}")
                        break
            return "\n\n".join(results) if results else "No results found."
        else:
            return "Wolfram Alpha couldn't process that query. Try rephrasing your math/computation question."
    except Exception as e:
        return f"Wolfram Alpha error: {e}"


def _check_copilot_available() -> bool:
    """Check if GitHub Copilot CLI is available."""
    try:
        import subprocess
        result = subprocess.run(["gh", "copilot", "--version"], capture_output=True, text=True)
        return result.returncode == 0
    except Exception:
        return False


def _check_wolfram_available() -> bool:
    """Check if Wolfram Alpha is configured."""
    import os
    return bool(os.getenv("WOLFRAM_APP_ID"))


def _check_dalle_available() -> bool:
    """Check if DALL-E is configured."""
    import os
    return bool(os.getenv("OPENAI_API_KEY"))


