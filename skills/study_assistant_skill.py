def open_colab(args: dict) -> str:
    """Open Google Colab with a notebook."""
    notebook_path = (args.get("notebook") or "").strip()
    new_notebook = bool(args.get("new", False))
    
    import tools
    
    if new_notebook or not notebook_path:
        # Open new empty Colab
        colab_url = f"{COLAB_BASE_URL}"
        tools.execute_tool("open_url", {"url": colab_url})
        return "Opening Google Colab with a new notebook."
    
    # Check if it's a GitHub notebook
    if "github.com" in notebook_path or notebook_path.endswith(".ipynb"):
        if "github.com" in notebook_path:
            # Convert GitHub URL to Colab format
            colab_url = notebook_path.replace("github.com", "github.com").replace("blob/", "")
            colab_url = f"https://colab.research.google.com/github/{colab_url.split('github.com/')[-1]}"
        else:
            colab_url = f"{COLAB_BASE_URL}/notebooks/{notebook_path}"
        
        tools.execute_tool("open_url", {"url": colab_url})
        return f"Opening notebook in Google Colab: {notebook_path}"
    
    # Local notebook - open Colab upload page
    tools.execute_tool("open_url", {"url": COLAB_BASE_URL})
    return f"Please upload your notebook to Colab. Local file: {notebook_path}"


